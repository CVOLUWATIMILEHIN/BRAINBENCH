/**
 * Reliable alphabetical sorting helper (A to Z by full course title).
 */
export function sortCoursesAlphabetically(courses: CourseItem[]): CourseItem[] {
  return [...courses].sort((a, b) =>
    a.title.localeCompare(b.title, undefined, { sensitivity: 'base' })
  );
}

